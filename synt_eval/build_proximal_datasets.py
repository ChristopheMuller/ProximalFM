Tensor = torch.Tensor

# Field order of RealisticProximalGenerator.get_batch. Indices 0..14 are the
# original 15; the Monte Carlo fields are appended last.
POOL_FIELDS = (
    "U X W Z A A_probs Y_obs Y0 Y1 d_U d_X d_W d_Z seq_lens train_sizes "
    "MU0 MU1 S2 K_eff"
).split()


# -----------------------------------------------------------------------------
# Mechanism allocation
# -----------------------------------------------------------------------------


def allocate_per_mechanism(
    n_datasets: int, mechanisms: Sequence[int]
) -> Dict[int, int]:
    """Spread ``n_datasets`` as evenly as possible across the given mechanisms."""
    m = len(mechanisms)
    base, rem = divmod(n_datasets, m)
    alloc = {}
    for i, mech_id in enumerate(mechanisms):
        alloc[mech_id] = base + (1 if i < rem else 0)
    return alloc


# -----------------------------------------------------------------------------
# Generation: produce one big pool of datasets, mixed across mechanisms
# -----------------------------------------------------------------------------


def generate_pool(
    gen: RealisticProximalGenerator,
    n_datasets: int,
    seq_len: int,
    train_size: int | float,
    mechanisms: Sequence[int],
    shuffle: bool = True,
) -> Tuple[Tuple[Tensor, ...], Tensor]:
    """Generate ``n_datasets`` datasets, balanced across ``mechanisms``.

    Returns
    -------
    pool : tuple of stacked tensors, in the same order as
        ``RealisticProximalGenerator.get_batch`` (19 fields).
    mech_ids : LongTensor [n_datasets] recording which mechanism made each set.
    seeds : LongTensor [n_datasets] holding each dataset's generator seed.
    """
    alloc = allocate_per_mechanism(n_datasets, mechanisms)

    chunks: List[Tuple[Tensor, ...]] = []
    mech_id_list: List[Tensor] = []
    seed_list: List[Tensor] = []
    for mech_id in mechanisms:
        k = alloc[mech_id]
        if k == 0:
            continue
        batch = gen.get_batch(
            mechanism_id=mech_id,
            batch_size=k,
            seq_len=seq_len,
            train_size=train_size,
        )
        chunks.append(batch)
        mech_id_list.append(torch.full((k,), mech_id, dtype=torch.long))
        # Mirrors the per-dataset seed get_batch derives internally, so the
        # sidecar can record which draw produced each episode.
        seed_list.append(
            int(gen.cfg.seed) + 100_000 * mech_id + torch.arange(k, dtype=torch.long)
        )

    if not chunks:
        raise ValueError("No datasets generated (check --n_datasets / --mechanisms).")

    # Concatenate each field across mechanism chunks (dim 0 = dataset).
    n_fields = len(chunks[0])
    pool = tuple(torch.cat([c[f] for c in chunks], dim=0) for f in range(n_fields))
    mech_ids = torch.cat(mech_id_list, dim=0)
    seeds = torch.cat(seed_list, dim=0)

    if shuffle:
        g = torch.Generator().manual_seed(int(gen.cfg.seed) + 7)
        perm = torch.randperm(mech_ids.shape[0], generator=g)
        pool = tuple(t[perm] for t in pool)
        mech_ids = mech_ids[perm]
        seeds = seeds[perm]

    return pool, mech_ids, seeds


# -----------------------------------------------------------------------------
# Training-validation format  ->  batch_*.pt (raw, sparse) + metadata.json
# -----------------------------------------------------------------------------


def _save_val_batch(pool: Tuple[Tensor, ...], idx: range, out_dir: Path, file_idx: int):
    """Write datasets ``idx`` as one ``batch_*.pt`` through the canonical writer.

    ``proximalfm.prior._genload.write_batch_file`` is the single writer of this
    format; this module used to carry a second copy of it, which is how the
    ``MU0``/``MU1``/``S2``/``K_eff`` fields went missing from every realistic set
    without anything failing.

    The writer stores whatever shape it is handed and does not move tensors off
    the accelerator, so the trailing-singleton squeeze and the ``.cpu()`` that
    the old copy folded in have to happen here instead.
    """
    p = dict(zip(POOL_FIELDS, pool))
    sl = slice(idx.start, idx.stop)

    def block(name: str) -> Tensor:
        # write_batch_file uses .view(), which refuses a non-contiguous input.
        return p[name][sl].cpu().contiguous()

    def col(name: str) -> Tensor:
        t = p[name][sl].cpu()
        if t.dim() == 3 and t.shape[-1] == 1:
            t = t.squeeze(-1)
        return t.contiguous()

    fields = {
        **{k: block(k) for k in ("U", "X", "W", "Z")},
        **{
            k: col(k) for k in ("A", "A_probs", "Y_obs", "Y0", "Y1", "MU0", "MU1", "S2")
        },
        **{
            k: p[k][sl].cpu()
            for k in ("d_U", "d_X", "d_W", "d_Z", "seq_lens", "train_sizes", "K_eff")
        },
    }
    write_batch_file(out_dir, file_idx, seq_len_per_gp=False, **fields)


def save_validation(
    pool: Tuple[Tensor, ...],
    out_dir: Path,
    cfg: RealisticGeneratorConfig,
    datasets_per_file: Optional[int],
    cli_command: str,
) -> Tuple[int, int]:
    """Write the val_dir of sparse batch_*.pt files + metadata.json.

    Returns ``(n_files, datasets_per_file)``.

    NOTE: ``LoadPriorDataset`` reconstructs each file to *that file's* max active
    feature dim, so files are only safe to consume one-at-a-time. If the loader
    ever has to concatenate two files (because a single file holds fewer datasets
    than the trainer's ``batch_size``) the feature widths can mismatch. We
    therefore default to a SINGLE file (``datasets_per_file = None``), which is
    always safe regardless of the training batch_size.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    B = pool[1].shape[0]
    T = int(pool[13][0].item())

    if datasets_per_file is None or datasets_per_file <= 0:
        datasets_per_file = B

    n_files = 0
    for file_idx, start in enumerate(range(0, B, datasets_per_file)):
        stop = min(start + datasets_per_file, B)
        _save_val_batch(pool, range(start, stop), out_dir, file_idx)
        n_files += 1

    # metadata.json mirrors SavePriorDataset.save_metadata (read by LoadPriorDataset).
    metadata = {
        "prior_type": "realistic_proximal_mechanisms",
        "batch_size": datasets_per_file,
        "batch_size_per_gp": 1,
        "min_seq_len": T,
        "max_seq_len": T,
        "log_seq_len": False,
        "seq_len_per_gp": False,
        "min_dim_U": cfg.min_dim_U,
        "max_dim_U": cfg.max_dim_U,
        "min_dim_W": cfg.min_dim_W,
        "max_dim_W": cfg.max_dim_W,
        "min_dim_Z": cfg.min_dim_Z,
        "max_dim_Z": cfg.max_dim_Z,
        "min_dim_X": cfg.min_dim_X,
        "max_dim_X": cfg.max_dim_X,
        "min_train_size": cfg.train_size,
        "max_train_size": cfg.train_size,
        "replay_small": False,
        # Written by SavePriorDataset and printed by LoadPriorDataset.__repr__;
        # the hand-rolled copy of this metadata used to omit both.
        "mc_cate": cfg.mc_cate,
        "mc_targets_on_context": False,
        "cli_command": cli_command,
    }
    with open(out_dir / "metadata.json", "w") as f:
        json.dump(metadata, f, indent=2)
    return n_files, datasets_per_file


# -----------------------------------------------------------------------------
# Manifest (human-readable record of what was built)
# -----------------------------------------------------------------------------


def write_manifest(
    root: Path,
    args: argparse.Namespace,
    mech_ids: Tensor,
    n_val_files: int,
    datasets_per_file: int,
    cli_command: str,
) -> None:
    counts = {
        RealisticProximalGenerator.mechanism_name(m): int((mech_ids == m).sum())
        for m in sorted(set(mech_ids.tolist()))
    }
    manifest = {
        "name": args.name,
        "n_datasets": int(mech_ids.shape[0]),
        "seq_len": args.seq_len,
        "prop_train": args.prop_train,
        # The same split, spelled the way prior_eval spells it.
        "n_max": args.n_max,
        "n_q": args.n_q,
        "seed": args.seed,
        "cli_command": cli_command,
        "mechanisms": args.mechanisms,
        "datasets_per_mechanism": counts,
        "datasets_per_val_file": datasets_per_file,
        "n_val_files": n_val_files,
        "val_dir": str((root / "val").resolve()),
    }
    with open(root / "manifest.json", "w") as f:
        json.dump(manifest, f, indent=2)


# -----------------------------------------------------------------------------
# Config (fully-resolved settings, incl. defaults, for reproducibility)
# -----------------------------------------------------------------------------


def write_config(
    root: Path,
    args: argparse.Namespace,
    mechanisms: Sequence[int],
    cli_command: str,
) -> None:
    """Dump every resolved setting (defaults filled in) to ``config.yaml``.

    Unlike the CLI string, this captures the *effective* value of each argument
    even when it was left at its default, so the build stays reproducible if the
    defaults change later. Re-run with ``--config config.yaml`` to reproduce.
    """
    config = dict(vars(args))
    # Drop the path to a *source* config; this file is the reproducible record.
    config.pop("config", None)
    # Persist the resolved mechanism list rather than the ``None`` sentinel.
    config["mechanisms"] = list(mechanisms)
    config["cli_command"] = cli_command
    with open(root / "config.yaml", "w") as f:
        yaml.safe_dump(config, f, sort_keys=True, default_flow_style=False)


