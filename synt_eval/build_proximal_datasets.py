"""
build_proximal_datasets.py

Materialize a FIXED set of "realistic" proximal datasets to disk, in the ONE
on-disk format the rest of the project consumes: a directory of raw, sparse
`batch_*.pt` files (+ metadata.json)  ->  <out_root>/<name>/val/ — exactly the
layout produced by `proximalfm.prior._genload.SavePriorDataset` and read back
by `LoadPriorDataset`.

The benchmark "test" report and the in-training "validation" pass can both
consume this directory, generated by `RealisticProximalGenerator` (see
realistic_proximal_mechanisms.py):

  * BENCHMARK — works on any build, `--mc_cate` or not. `run.py`
    rebuilds its standardized dict from the raw files at load time (see
    benchmarks/data.py). Point a benchmark at it with:

        data:
          source: load
          val_dir: <out_root>/<name>/val

  * TRAINING-VALIDATION — needs `--mc_cate K` (`K > 1`); see below. Point the
    trainer at the build's *root* with `--synt_eval_dir <out_root>/<name>`.

Datasets are spread as evenly as possible across the 12 realistic mechanisms.
The whole build is reproducible from `--seed`: generate a "validation batch" and
a never-before-seen "test batch" simply by using two different seeds (and, by
convention, two different `--name`s / output folders).

Example
-------
    # Validation batch (seen during training to tune the model)
    python synt_eval/build_proximal_datasets.py \
        --name proximal_val_v1 --n_datasets 240 --seq_len 2048 \
        --prop_train 0.75 --seed 123

    # Test batch (held out; only used for final comparison)
    python synt_eval/build_proximal_datasets.py \
        --name proximal_test_v1 --n_datasets 240 --seq_len 2048 \
        --prop_train 0.75 --seed 9999

Each build also writes a fully-resolved ``config.yaml`` (all settings, including
those left at their defaults). Re-run an earlier build exactly, even if defaults
have since changed, by pointing ``--config`` at it (explicit flags still win):

    python synt_eval/build_proximal_datasets.py \
        --config data/synt_eval/proximal_val_v1/config.yaml --name proximal_val_v2

Replicate mode (``--mc_cate K`` with ``K > 1``)
----------------------------------------------

Without it (the default, ``K=1``), a set carries only realized potential
outcomes: ``Y1 - Y0`` is a draw of the *ITE*, and ``MU0``/``MU1`` are written as
those same draws. No sidecar is written. Such a set is usable by the benchmark
harness, but **not** by the trainer: `--synt_eval_dir` requires `frozen_meta.pt`
and refuses a set without one, rather than silently scoring point or
distributional metrics against sampled ITEs.

With ``K > 1`` each query row is replicated through the latent and noise draw,
``MU0``/``MU1`` become Monte Carlo estimates of ``E[Y_a | X]`` and ``S2`` their
paired sampling variance -- see the estimand section of
``realistic_proximal_mechanisms``. The build then also writes the
``frozen_meta.pt`` sidecar, which is what makes the set usable for training
validation at all: the trainer's `--synt_eval_dir` scores it once and emits both
``synt_point/*`` and ``synt_dist/*`` from that single pass::

    --synt_eval_dir <out_root>/<name>  # the ROOT, not its val/

    python synt_eval/build_proximal_datasets.py \
        --name proximal_dist_v1 --n_datasets 480 --seq_len 2048 \
        --prop_train 0.75 --mc_cate 1000 --seed 20260807

Memory scales as ``N = n_ctx + n_q*K`` rows per dataset (one dataset at a time,
not the whole batch), and an unaffordable ``K`` raises rather than being capped.

Because ``n_q`` is what trades against ``K``, the row split can also be given
directly as ``--n_max C --n_q Q`` -- the spelling ``prior_eval`` uses -- instead
of ``--seq_len``/``--prop_train``. It is a front-end spelling of the same one
number the generator takes: it resolves to ``seq_len = n_max + n_q`` and
``prop_train = n_max / seq_len`` exactly, so either spelling of a given split
builds the same set with the same ``content_digest``. Pass one or the other; the
builder refuses a mix.
"""

