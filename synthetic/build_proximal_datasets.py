"""
build_proximal_datasets.py

Materialize a FIXED set of "realistic" proximal datasets to disk, in the two
on-disk formats the rest of the project consumes:

  (1) BENCHMARK format  ->  <out_root>/<name>/benchmark/data.pt
      A single standardized dict, identical in schema to what
      `benchmarks/bench_run.py::_generate_data` writes. Point a benchmark at it
      with:

          data:
            source: load
            output_dir: <out_root>/<name>/benchmark

  (2) TRAINING-VALIDATION format  ->  <out_root>/<name>/val/batch_000000.pt ...
      A directory of sparse `batch_*.pt` files (+ metadata.json), exactly the
      layout produced by `proximalfm.prior._genload.SavePriorDataset` and read
      back by `LoadPriorDataset`. Point the trainer at it with:

          --val_dir <out_root>/<name>/val

Both outputs are built from the SAME underlying datasets, generated by
`RealisticProximalGenerator` (see realistic_proximal_mechanisms.py), so the
benchmark "test" report and the in-training "validation" pass see the same DGPs.

Datasets are spread as evenly as possible across the 12 realistic mechanisms.
The whole build is reproducible from `--seed`: generate a "validation batch" and
a never-before-seen "test batch" simply by using two different seeds (and, by
convention, two different `--name`s / output folders).

Example
-------
    # Validation batch (seen during training to tune the model)
    python synthetic/build_proximal_datasets.py \
        --name proximal_val_v1 --n_datasets 240 --seq_len 2048 \
        --prop_train 0.75 --seed 123

    # Test batch (held out; only used for final comparison)
    python synthetic/build_proximal_datasets.py \
        --name proximal_test_v1 --n_datasets 240 --seq_len 2048 \
        --prop_train 0.75 --seed 9999
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import torch

from realistic_proximal_mechanisms import (
    N_MECHANISMS,
    RealisticGeneratorConfig,
    RealisticProximalGenerator,
)

Tensor = torch.Tensor


# -----------------------------------------------------------------------------
# Sparse helper (must match proximalfm.prior._genload.sparse2dense exactly, as
# that is the function LoadPriorDataset uses to reconstruct the val tensors).
# -----------------------------------------------------------------------------


def dense2sparse(dense: Tensor, row_lengths: Tensor, dtype=torch.float32) -> Tensor:
    """Drop padding columns: keep the first ``row_lengths[i]`` entries of row i."""
    assert dense.dim() == 2, "dense must be 2D"
    num_rows, num_cols = dense.shape
    assert row_lengths.shape[0] == num_rows
    assert (row_lengths <= num_cols).all()
    idx = torch.arange(num_cols, device=dense.device)
    mask = idx.unsqueeze(0) < row_lengths.unsqueeze(1)
    return dense[mask].to(dtype)


# -----------------------------------------------------------------------------
# Mechanism allocation
# -----------------------------------------------------------------------------


def allocate_per_mechanism(
    n_datasets: int, mechanisms: Sequence[int]
) -> Dict[int, int]:
    """Spread ``n_datasets`` as evenly as possible across the given mechanisms."""
    m = len(mechanisms)
    base, rem = divmod(n_datasets, m)
    alloc = {}
    for i, mech_id in enumerate(mechanisms):
        alloc[mech_id] = base + (1 if i < rem else 0)
    return alloc


# -----------------------------------------------------------------------------
# Generation: produce one big pool of datasets, mixed across mechanisms
# -----------------------------------------------------------------------------


def generate_pool(
    gen: RealisticProximalGenerator,
    n_datasets: int,
    seq_len: int,
    train_size: int | float,
    mechanisms: Sequence[int],
    shuffle: bool = True,
) -> Tuple[Tuple[Tensor, ...], Tensor]:
    """Generate ``n_datasets`` datasets, balanced across ``mechanisms``.

    Returns
    -------
    pool : tuple of stacked tensors, in the same 15-object order as
        ``RealisticProximalGenerator.get_batch``.
    mech_ids : LongTensor [n_datasets] recording which mechanism made each set.
    """
    alloc = allocate_per_mechanism(n_datasets, mechanisms)

    chunks: List[Tuple[Tensor, ...]] = []
    mech_id_list: List[Tensor] = []
    for mech_id in mechanisms:
        k = alloc[mech_id]
        if k == 0:
            continue
        batch = gen.get_batch(
            mechanism_id=mech_id,
            batch_size=k,
            seq_len=seq_len,
            train_size=train_size,
        )
        chunks.append(batch)
        mech_id_list.append(torch.full((k,), mech_id, dtype=torch.long))

    if not chunks:
        raise ValueError("No datasets generated (check --n_datasets / --mechanisms).")

    # Concatenate each of the 15 tensors across mechanism chunks (dim 0 = dataset).
    n_fields = len(chunks[0])
    pool = tuple(torch.cat([c[f] for c in chunks], dim=0) for f in range(n_fields))
    mech_ids = torch.cat(mech_id_list, dim=0)

    if shuffle:
        g = torch.Generator().manual_seed(int(gen.cfg.seed) + 7)
        perm = torch.randperm(mech_ids.shape[0], generator=g)
        pool = tuple(t[perm] for t in pool)
        mech_ids = mech_ids[perm]

    return pool, mech_ids


# -----------------------------------------------------------------------------
# (1) Benchmark format  ->  data.pt  (standardized, single file)
# -----------------------------------------------------------------------------


def _safe_standardize_context(x: Tensor, train_size: int) -> Tensor:
    """Standardize using ONLY the first ``train_size`` rows (no test leakage)."""
    if x.shape[-1] == 0:
        return x
    ctx = x[:, :train_size]
    mu = ctx.mean(dim=1, keepdim=True)
    std = ctx.std(dim=1, keepdim=True)
    std = torch.where(std < 1e-5, torch.ones_like(std), std)
    return (x - mu) / std


def save_benchmark(pool: Tuple[Tensor, ...], out_dir: Path) -> Path:
    """Write the standardized single-file `data.pt` consumed by bench_run.py."""
    (
        U,
        X,
        W,
        Z,
        A,
        A_probs,
        Y_obs,
        Y0,
        Y1,
        d_U,
        d_X,
        d_W,
        d_Z,
        seq_lens,
        train_sizes,
    ) = pool

    B, T, _ = X.shape
    train_size = int(train_sizes[0].item())
    n_test = T - train_size

    X_std = _safe_standardize_context(X, train_size)
    W_std = _safe_standardize_context(W, train_size)
    Z_std = _safe_standardize_context(Z, train_size)
    U_std = _safe_standardize_context(U, train_size)

    y_train_obs = Y_obs[:, :train_size]
    y_ctx_mean = y_train_obs.mean(dim=1, keepdim=True)
    y_ctx_std = y_train_obs.std(dim=1, unbiased=False, keepdim=True).clamp(min=1e-5)
    Y_obs_std = (Y_obs - y_ctx_mean) / y_ctx_std

    true_ITEs_std = (
        ((Y1[:, train_size:] - Y0[:, train_size:]) / y_ctx_std).cpu().numpy()
    )

    data = {
        "U": U_std.cpu(),
        "X": X_std.cpu(),
        "Z": Z_std.cpu(),
        "W": W_std.cpu(),
        "A": A.cpu(),
        "Y": Y_obs_std.cpu(),
        "d_X": d_X.cpu(),
        "d_Z": d_Z.cpu(),
        "d_W": d_W.cpu(),
        "true_ITEs": true_ITEs_std,
        "N_TRAIN": train_size,
        "N_TEST": n_test,
        "N_BATCH": B,
    }

    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / "data.pt"
    tmp = out_dir / "data.pt.tmp"
    torch.save(data, tmp)
    tmp.replace(path)
    return path


# -----------------------------------------------------------------------------
# (2) Training-validation format  ->  batch_*.pt (raw, sparse) + metadata.json
# -----------------------------------------------------------------------------


def _save_val_batch(pool: Tuple[Tensor, ...], idx: range, batch_file: Path) -> None:
    """Sparse-encode datasets ``idx`` and write one batch_*.pt (raw, unscaled)."""
    (
        U,
        X,
        W,
        Z,
        A,
        A_probs,
        Y_obs,
        Y0,
        Y1,
        d_U,
        d_X,
        d_W,
        d_Z,
        seq_lens,
        train_sizes,
    ) = pool

    sl = slice(idx.start, idx.stop)
    U_b, X_b, W_b, Z_b = U[sl], X[sl], W[sl], Z[sl]
    d_U_b, d_X_b, d_W_b, d_Z_b = d_U[sl], d_X[sl], d_W[sl], d_Z[sl]
    B, T, _ = X_b.shape

    # Sparse encode covariates/proxies (non-nested path expected by LoadPriorDataset).
    U_sp = dense2sparse(U_b.reshape(-1, U_b.shape[-1]), d_U_b.repeat_interleave(T))
    X_sp = dense2sparse(X_b.reshape(-1, X_b.shape[-1]), d_X_b.repeat_interleave(T))
    W_sp = dense2sparse(W_b.reshape(-1, W_b.shape[-1]), d_W_b.repeat_interleave(T))
    Z_sp = dense2sparse(Z_b.reshape(-1, Z_b.shape[-1]), d_Z_b.repeat_interleave(T))

    def _btt(t: Tensor) -> Tensor:
        t = t[sl].cpu()
        if t.dim() == 3 and t.shape[-1] == 1:
            t = t.squeeze(-1)
        return t

    payload = {
        "U": U_sp,
        "X": X_sp,
        "W": W_sp,
        "Z": Z_sp,
        "A": _btt(A),
        "A_probs": _btt(A_probs),
        "Y_obs": _btt(Y_obs),
        "Y0": _btt(Y0),
        "Y1": _btt(Y1),
        "d_U": d_U_b.cpu(),
        "d_X": d_X_b.cpu(),
        "d_W": d_W_b.cpu(),
        "d_Z": d_Z_b.cpu(),
        "seq_lens": seq_lens[sl].cpu(),
        "train_sizes": train_sizes[sl].cpu(),
        "batch_size": B,
    }
    tmp = batch_file.with_suffix(".pt.tmp")
    torch.save(payload, tmp)
    tmp.replace(batch_file)


def save_validation(
    pool: Tuple[Tensor, ...],
    out_dir: Path,
    cfg: RealisticGeneratorConfig,
    datasets_per_file: Optional[int],
) -> Tuple[int, int]:
    """Write the val_dir of sparse batch_*.pt files + metadata.json.

    Returns ``(n_files, datasets_per_file)``.

    NOTE: ``LoadPriorDataset`` reconstructs each file to *that file's* max active
    feature dim, so files are only safe to consume one-at-a-time. If the loader
    ever has to concatenate two files (because a single file holds fewer datasets
    than the trainer's ``batch_size``) the feature widths can mismatch. We
    therefore default to a SINGLE file (``datasets_per_file = None``), which is
    always safe regardless of the training batch_size.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    B = pool[1].shape[0]
    T = int(pool[13][0].item())

    if datasets_per_file is None or datasets_per_file <= 0:
        datasets_per_file = B

    n_files = 0
    for file_idx, start in enumerate(range(0, B, datasets_per_file)):
        stop = min(start + datasets_per_file, B)
        batch_file = out_dir / f"batch_{file_idx:06d}.pt"
        _save_val_batch(pool, range(start, stop), batch_file)
        n_files += 1

    # metadata.json mirrors SavePriorDataset.save_metadata (read by LoadPriorDataset).
    metadata = {
        "prior_type": "realistic_proximal_mechanisms",
        "batch_size": datasets_per_file,
        "batch_size_per_gp": 1,
        "min_seq_len": T,
        "max_seq_len": T,
        "log_seq_len": False,
        "seq_len_per_gp": False,
        "min_dim_U": cfg.min_dim_U,
        "max_dim_U": cfg.max_dim_U,
        "min_dim_W": cfg.min_dim_W,
        "max_dim_W": cfg.max_dim_W,
        "min_dim_Z": cfg.min_dim_Z,
        "max_dim_Z": cfg.max_dim_Z,
        "min_dim_X": cfg.min_dim_X,
        "max_dim_X": cfg.max_dim_X,
        "min_train_size": cfg.train_size,
        "max_train_size": cfg.train_size,
        "replay_small": False,
    }
    with open(out_dir / "metadata.json", "w") as f:
        json.dump(metadata, f, indent=2)
    return n_files, datasets_per_file


# -----------------------------------------------------------------------------
# Manifest (human-readable record of what was built)
# -----------------------------------------------------------------------------


def write_manifest(
    root: Path,
    args: argparse.Namespace,
    mech_ids: Tensor,
    n_val_files: int,
    datasets_per_file: int,
) -> None:
    counts = {
        RealisticProximalGenerator.mechanism_name(m): int((mech_ids == m).sum())
        for m in sorted(set(mech_ids.tolist()))
    }
    manifest = {
        "name": args.name,
        "n_datasets": int(mech_ids.shape[0]),
        "seq_len": args.seq_len,
        "prop_train": args.prop_train,
        "seed": args.seed,
        "mechanisms": args.mechanisms,
        "datasets_per_mechanism": counts,
        "datasets_per_val_file": datasets_per_file,
        "n_val_files": n_val_files,
        "benchmark_dir": str((root / "benchmark").resolve()),
        "val_dir": str((root / "val").resolve()),
    }
    with open(root / "manifest.json", "w") as f:
        json.dump(manifest, f, indent=2)


# -----------------------------------------------------------------------------
# Main
# -----------------------------------------------------------------------------


def build(args: argparse.Namespace) -> None:
    mechanisms = args.mechanisms or list(range(1, N_MECHANISMS + 1))
    for m in mechanisms:
        if not 1 <= m <= N_MECHANISMS:
            raise ValueError(f"mechanism id {m} out of range 1..{N_MECHANISMS}")

    root = Path(args.out_root) / args.name
    bench_dir = root / "benchmark"
    val_dir = root / "val"

    cfg = RealisticGeneratorConfig(
        save_dir=str(root / "_gen_scratch"),
        K=args.n_datasets,
        seq_len=args.seq_len,
        train_size=args.prop_train,
        min_dim_U=args.min_dim_U,
        max_dim_U=args.max_dim_U,
        min_dim_X=args.min_dim_X,
        max_dim_X=args.max_dim_X,
        min_dim_W=args.min_dim_W,
        max_dim_W=args.max_dim_W,
        min_dim_Z=args.min_dim_Z,
        max_dim_Z=args.max_dim_Z,
        seed=args.seed,
        device="cpu",
    )
    gen = RealisticProximalGenerator(cfg)

    print(
        f"Building '{args.name}': {args.n_datasets} datasets x T={args.seq_len} "
        f"across {len(mechanisms)} mechanisms (seed={args.seed})…"
    )

    pool, mech_ids = generate_pool(
        gen,
        n_datasets=args.n_datasets,
        seq_len=args.seq_len,
        train_size=args.prop_train,
        mechanisms=mechanisms,
        shuffle=not args.no_shuffle,
    )

    bench_path = save_benchmark(pool, bench_dir)
    print(f"  [benchmark] {bench_path}  (source: load, output_dir: {bench_dir})")

    n_val_files, dpf = save_validation(pool, val_dir, cfg, args.datasets_per_file)
    print(f"  [validation] {n_val_files} file(s) in {val_dir}  (--val_dir {val_dir})")

    write_manifest(root, args, mech_ids, n_val_files, dpf)
    print(f"  [manifest]  {root / 'manifest.json'}")


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    p.add_argument(
        "--name",
        type=str,
        required=True,
        help="Subfolder / identifier for this fixed dataset batch "
        "(e.g. proximal_val_v1, proximal_test_v1).",
    )
    p.add_argument(
        "--out_root",
        type=str,
        default="synthetic/datasets",
        help="Root directory under which <name>/{benchmark,val} are written.",
    )
    p.add_argument(
        "--n_datasets",
        type=int,
        default=240,
        help="Total number of datasets, split evenly across mechanisms.",
    )
    p.add_argument("--seq_len", type=int, default=2048, help="Rows per dataset.")
    p.add_argument(
        "--prop_train",
        type=float,
        default=0.75,
        help="Fraction of rows used as training context (rest = query/test).",
    )
    p.add_argument(
        "--seed",
        type=int,
        default=123,
        help="Master seed. Use different seeds for the validation vs test batch.",
    )
    p.add_argument(
        "--mechanisms",
        type=int,
        nargs="*",
        default=None,
        help=f"Subset of mechanism ids 1..{N_MECHANISMS} (default: all).",
    )
    p.add_argument(
        "--datasets_per_file",
        type=int,
        default=None,
        help="Datasets per val batch_*.pt file. Default: all in one file "
        "(safest). If you split, each file MUST hold >= the trainer's "
        "batch_size, or LoadPriorDataset will fail to merge files.",
    )
    p.add_argument(
        "--no_shuffle",
        action="store_true",
        help="Keep datasets grouped by mechanism instead of interleaving.",
    )

    # Dimension ranges
    p.add_argument("--min_dim_U", type=int, default=1)
    p.add_argument("--max_dim_U", type=int, default=10)
    p.add_argument("--min_dim_X", type=int, default=1)
    p.add_argument("--max_dim_X", type=int, default=10)
    p.add_argument("--min_dim_W", type=int, default=1)
    p.add_argument("--max_dim_W", type=int, default=10)
    p.add_argument("--min_dim_Z", type=int, default=1)
    p.add_argument("--max_dim_Z", type=int, default=10)
    return p


if __name__ == "__main__":
    build(build_parser().parse_args())
