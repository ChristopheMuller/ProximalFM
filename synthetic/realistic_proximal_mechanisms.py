"""
realistic_proximal_mechanisms.py

Realistic data-generating families for proximal causal learning.

Every mechanism is a plausible real-world data-generating process 
(clinical, economic, marketing, education, epidemiological). 

All mechanisms obey the proximal causal skeleton implied by Tchetgen Tchetgen
et al., "An Introduction to Proximal Causal Learning":

    X ............. measured Type-(a) common causes  (mixed tabular types)
    U ............. UNMEASURED confounder (severity / type / frailty / ability)
    Z = f_Z(X, U) + noise ........ treatment-inducing proxy  (Type b)
    W = f_W(X, U) + noise ........ outcome-inducing  proxy   (Type c, pre-treatment)
    A ~ Bernoulli(sigmoid(g_A(X, U, Z))) ......... NO direct W input
    Y(a) = g_Y(a, X, U, W) + shared_noise ........ NO direct Z input
    Y_obs = A * Y1 + (1 - A) * Y0

The structural exclusions enforce the negative-control conditions:

    NC.1   Y  _||_ Z | A, U, X
    NC.2   W  _||_ (A, Z) | U, X

and every mechanism guarantees:

    * U enters BOTH g_A and g_Y with non-trivial weight  -> real confounding,
    * U has variance orthogonal to X (independent noise)  -> X-adjustment is
      insufficient, so the bias survives backdoor on the measured covariates,
    * Z and W load on U strongly enough to be U-relevant   -> proximal
      identification is possible,
    * dim(Z), dim(W) >= dim(U)                              -> categorical
      completeness `min(d_Z, d_W) >= d_U`.

Output contract -- get_batch returns 19 objects; indices 0..14 are the original
15 and the Monte Carlo target fields are appended last, so existing positional
readers stay valid:

    U, X, W, Z, A, A_probs, Y_obs, Y0, Y1,
    d_U, d_X, d_W, d_Z, seq_lens, train_sizes,
    MU0, MU1, S2, K_eff


Replicate mode and the estimand (ROADMAP B1)
--------------------------------------------

With ``mc_cate = K > 1`` each *query* row is replicated ``K`` times through the
latent and noise draw with its covariate row held fixed, and the target is

    tau*(x) = E[ Y1 - Y0 | X = x ]

i.e. the expectation is taken over U, over W, and over the outcome noise. This
is not a free choice: it is exactly the estimand
``SCMPrior.generate_dataset`` supervises the model on
(``proximalfm/prior/_dataset.py``, which replicates ``X`` and re-runs ``f_U``
*and* ``f_W`` per replicate). Scoring a posterior against any other conditional
-- notably ``E[Y1 - Y0 | X, W, Z]``, which the ROADMAP originally proposed --
measures a different object than the one the model was fit to, and a perfectly
calibrated model then reads as systematically over-wide.

Matching the prior also makes the target *forward-samplable*: everything
downstream of X is generated by ancestral sampling, whereas conditioning on the
row's realized W would require the posterior ``U | X, W, Z`` and hence MCMC.

Consequences per mechanism, worth knowing before reading any number:

* ``Z`` never enters ``Y0``/``Y1`` in any of the twelve, and ``A`` never enters
  either, so both are *leaves* w.r.t. the target and are generated on the
  ``T`` observed rows only. (Mechanism 3 is the near-miss: ``latent_risk``
  feeds both the effect modifier and, via ``risk_score``, the assignment --
  but ``Z`` joins only in ``risk_score``.)
* For the additive-``tau`` mechanisms (1, 2, 3, 7, 9, 10, 11, 12) the shared
  ``eps`` cancels in ``Y1 - Y0``, so the per-replicate spread reflects only the
  latent draw. For 4, 5, 6 and 8 the ``exp``/``clamp``/zero-inflation links mean
  it does not cancel and the Monte Carlo average is doing real work.
* Latents that are *not* observed by any consumer are marginalized, not held
  fixed: mechanism 2's subtype, 6's ``active`` zero-inflation flag, 9's site,
  and 12's ``is_null`` spike. In particular 12's realized ITE is a spike-and-slab
  draw while ``tau*`` is smooth and near-zero -- learning the latter out of the
  former is the point of that mechanism, not a defect of it.
* Mechanism 9's ``tau`` is a deterministic function of X alone, so its Monte
  Carlo variance is exactly zero. Mechanism 12's ``tau*`` has the closed form
  ``(1 - null_frac) * c * tanh(lin(X))``. Both are used as correctness checks.
* Dataset-level empirical statistics (``_standardize``, ``_bounded_ordinal``'s
  quantile thresholds, mechanism 3's ``latent_cut`` and 5's censoring
  ``horizon``) are frozen on the ``T`` *observed* rows and broadcast to the
  replicates. They define mechanism structure, so freezing them keeps ``K`` a
  pure variance-reduction knob rather than something that moves the estimand.
* ``extra_observation_noise`` is added to ``Y_obs`` only, never to the
  structural ``Y0``/``Y1`` the target is built from.

``mc_cate = 1`` is the legacy path: no replication, and ``MU0``/``MU1`` are the
single realized draw, reproducing byte-for-byte what this module emitted before
replicate mode existed. Such a set carries no Monte Carlo CATE target and must
not be scored distributionally; the gate for that is the absence of the
``frozen_meta.pt`` sidecar, which only a ``K > 1`` build writes.
"""

