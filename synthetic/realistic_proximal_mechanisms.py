@dataclass
class RealisticGeneratorConfig:
    save_dir: str | Path

    # Independently parameterized datasets per mechanism batch.
    K: int = 10

    # Rows per synthetic dataset.
    seq_len: int = 2048

    # Integer number of training rows, or float fraction of seq_len.
    train_size: int | float = 0.5

    min_dim_U: int = 1
    max_dim_U: int = 3
    min_dim_X: int = 1
    max_dim_X: int = 8
    min_dim_W: int = 1
    max_dim_W: int = 8
    min_dim_Z: int = 1
    max_dim_Z: int = 8

    dim_U_distribution: str = "triangular"

    # Strict positivity floor: propensities mapped to [overlap_eps, 1 - overlap_eps].
    overlap_eps: float = 0.02

    # Clamp standardized logits before sigmoid for numerical stability.
    logit_clip: float = 6.0

    # Measurement noise added to OBSERVED labels only (Y0/Y1 stay structural).
    extra_observation_noise: float = 0.03
    missing_prob: float = 0.0

    # Lower bound on how strongly U must drive treatment and outcome.
    # Mechanisms scale their U-coefficients to respect this floor.
    min_confounding_strength: float = 0.8

    # Monte Carlo replicates per query row. 1 = legacy (no replication, and no
    # CATE target). >1 turns on replicate mode; see the module docstring.
    mc_cate: int = 1

    # Element budget for the transient N-row replicate block. Exceeding it
    # raises rather than silently capping K -- see _check_mc_budget.
    mc_mem_budget: int = 2_000_000_000

    seed: int = 123
    device: str = "cpu"
    dtype: torch.dtype = torch.float32

    seq_len_per_gp: bool = False


N_MECHANISMS = 12


class MonteCarloBudgetError(RuntimeError):
    """Raised when the requested ``mc_cate`` exceeds the memory budget."""


# Live float32 columns per replicate row, summed over the widest mechanism:
# X, U (raw + standardized + gamma temporaries), W (raw + standardized +
# ordinal temporary), one MLP hidden activation, and ~12 single-column
# intermediates (f0, tau, eps, Y0, Y1, latent_risk, ...). A calibration dial for
# the budget check, not a hard ceiling; measured RSS runs above it.
_COLS_PER_ROW = 96


@dataclass(frozen=True)
class _Rep:
    """Replicate layout for one dataset.

    Row layout of every N-row tensor, matching ``SCMPrior.generate_dataset``::

        [ ctx 0 .. n_ctx-1 ][ q0 x K ][ q1 x K ] ... [ q_{n_q-1} x K ]

    The replicate block is a contiguous suffix, so the Monte Carlo reduction is
    a single ``view(n_q, K).mean(1)`` and needs no gather -- and ``view``, which
    raises on a non-contiguous layout, doubles as the layout assertion.

    ``obs_idx`` maps each logical row to the replicate row realized as the
    *observed* world: identity on the context prefix, one randomly chosen
    replicate per query row.
    """

    T: int
    n_ctx: int
    n_q: int
    K: int
    N: int
    obs_idx: Tensor

    @property
    def replicated(self) -> bool:
        return self.K > 1


# -----------------------------------------------------------------------------
# Generator
# -----------------------------------------------------------------------------


class RealisticProximalGenerator:
    """Generate and save realistic proximal data-generating families."""

    def __init__(self, config: RealisticGeneratorConfig):
        self.cfg = config
        self.save_dir = Path(config.save_dir)
        self.save_dir.mkdir(parents=True, exist_ok=True)

        self.rng = torch.Generator(device="cpu")
        self.rng.manual_seed(int(config.seed))

        self.device = torch.device(config.device)
        self.dtype = config.dtype

        if config.seq_len_per_gp:
            raise NotImplementedError(
                "Set seq_len_per_gp=False for fixed-length batches."
            )
        if int(config.mc_cate) < 1:
            raise ValueError("mc_cate must be >= 1")

        # Replaced per dataset by generate_dataset. The legacy default keeps the
        # row-count helpers well-defined if a mechanism is driven directly.
        self._rep = self._legacy_rep(1)
        # Closed-form quantities a mechanism can expose for tests. Written
        # without consuming RNG, so it never perturbs the generated data.
        self._debug: Dict[str, Tensor] = {}

        self._check_dims()

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def get_batch(
        self,
        mechanism_id: int,
        batch_size: Optional[int] = None,
        seq_len: Optional[int] = None,
        train_size: Optional[int | float] = None,
    ) -> Tuple[Tensor, ...]:
        if not 1 <= mechanism_id <= N_MECHANISMS:
            raise ValueError(f"mechanism_id must be in 1..{N_MECHANISMS}")

        B = int(batch_size or self.cfg.K)
        T = int(seq_len or self.cfg.seq_len)
        train_n = self._resolve_train_size(
            train_size if train_size is not None else self.cfg.train_size, T
        )

        results = []
        for ds_idx in range(B):
            seed = int(self.cfg.seed + 100_000 * mechanism_id + ds_idx)
            params = {
                "mechanism_id": mechanism_id,
                "seq_len": T,
                "train_size": train_n,
                "dataset_seed_index": ds_idx,
                "seed": seed,
            }
            with self._with_seed(seed):
                results.append(self.generate_dataset(params))

        (
            U_list,
            X_list,
            W_list,
            Z_list,
            A_list,
            A_probs_list,
            Y_obs_list,
            Y0_list,
            Y1_list,
            d_U_list,
            d_X_list,
            d_W_list,
            d_Z_list,
            MU0_list,
            MU1_list,
            S2_list,
            K_eff_list,
        ) = zip(*results)

        U = torch.stack(U_list).to(self.device)
        X = torch.stack(X_list).to(self.device)
        W = torch.stack(W_list).to(self.device)
        Z = torch.stack(Z_list).to(self.device)
        A = torch.stack(A_list).to(self.device)
        A_probs = torch.stack(A_probs_list).to(self.device)
        Y_obs = torch.stack(Y_obs_list).to(self.device)
        Y0 = torch.stack(Y0_list).to(self.device)
        Y1 = torch.stack(Y1_list).to(self.device)
        MU0 = torch.stack(MU0_list).to(self.device)
        MU1 = torch.stack(MU1_list).to(self.device)
        S2 = torch.stack(S2_list).to(self.device)
        K_eff = torch.stack(K_eff_list).to(self.device)

        d_U = torch.stack(d_U_list).to(self.device)
        d_X = torch.stack(d_X_list).to(self.device)
        d_W = torch.stack(d_W_list).to(self.device)
        d_Z = torch.stack(d_Z_list).to(self.device)

        seq_lens = torch.full((B,), T, device=self.device, dtype=torch.long)
        train_sizes = torch.full((B,), train_n, device=self.device, dtype=torch.long)

        self._validate_batch_shapes(
            U=U,
            X=X,
            W=W,
            Z=Z,
            A=A,
            A_probs=A_probs,
            Y_obs=Y_obs,
            Y0=Y0,
            Y1=Y1,
            MU0=MU0,
            MU1=MU1,
            S2=S2,
            d_U=d_U,
            d_X=d_X,
            d_W=d_W,
            d_Z=d_Z,
            seq_lens=seq_lens,
            train_sizes=train_sizes,
        )

        # MU0/MU1/S2/K_eff are appended last deliberately: indices 0..14 stay
        # exactly what they were before replicate mode, so positional readers of
        # the original 15-tuple keep working.
        return (
            U,
            X,
            W,
            Z,
            A,
            A_probs,
            Y_obs,
            Y0,
            Y1,
            d_U,
            d_X,
            d_W,
            d_Z,
            seq_lens,
            train_sizes,
            MU0,
            MU1,
            S2,
            K_eff,
        )

    # ------------------------------------------------------------------
    # Replicate mode
    # ------------------------------------------------------------------

    @staticmethod
    def _legacy_rep(T: int) -> _Rep:
        """The K=1 layout: no replication, and no RNG consumed building it."""
        return _Rep(T=T, n_ctx=T, n_q=0, K=1, N=T, obs_idx=torch.arange(T))

    def _check_mc_budget(self, n_ctx: int, n_q: int, K: int) -> None:
        """Refuse a build that cannot afford the requested K.

        The prior caps-and-warns (``SCMPrior._cap_mc_samples``) because it
        generates online, where a noisier target beats a crashed run. A frozen
        realistic set is the opposite object: an offline, byte-reproducible
        artifact whose whole value is a *documented, uniform* K. A silent
        per-dataset cap would make K_eff vary across datasets and across
        machines, invisibly, and every calibration number downstream would be
        scored against a target noisier than the sidecar claims.
        """
        N = n_ctx + n_q * K
        elements = N * _COLS_PER_ROW
        if elements <= int(self.cfg.mc_mem_budget):
            return
        raise MonteCarloBudgetError(
            f"mc_cate={K} needs N = n_ctx + n_q*K = {n_ctx:,} + {n_q:,}*{K} = "
            f"{N:,} replicate rows (~{elements * 4 / 1e9:.1f} GB at "
            f"{_COLS_PER_ROW} float32 cols/row), over mc_mem_budget="
            f"{int(self.cfg.mc_mem_budget):,} elements. Lower --mc_cate, or "
            "lower n_q by raising the train fraction (n_q = seq_len - "
            "train_size), or raise the budget."
        )

    def _make_rep(self, T: int, train_n: int) -> _Rep:
        """Build the replicate layout for one dataset, drawing ``obs_idx``.

        At K=1 this consumes **no** RNG -- deliberately unlike the prior, which
        draws its ``obs_k`` unconditionally. That draw would advance the
        generator and desynchronise every downstream tensor from what this
        module emitted before replicate mode, breaking the legacy set.
        """
        K = int(self.cfg.mc_cate)
        if K == 1:
            return self._legacy_rep(T)

        # train_size is metadata elsewhere and is not guaranteed to be < T;
        # clamp so at least one query row survives (else view(0, K) and an
        # empty torch.quantile).
        n_ctx = max(0, min(int(train_n), T - 1))
        n_q = T - n_ctx
        self._check_mc_budget(n_ctx, n_q, K)

        obs_k = torch.randint(K, size=(n_q,), generator=self.rng)
        obs_idx = torch.cat(
            [
                torch.arange(n_ctx),
                n_ctx + torch.arange(n_q) * K + obs_k,
            ]
        )
        return _Rep(T=T, n_ctx=n_ctx, n_q=n_q, K=K, N=n_ctx + n_q * K, obs_idx=obs_idx)

    def _replicate(self, x: Tensor) -> Tensor:
        """``(T, d) -> (N, d)``: hold each query row fixed across K replicates.

        Broadcast straight into one preallocated buffer; an ``expand().reshape()``
        plus a ``cat`` would copy the query block twice.
        """
        r = self._rep
        if not r.replicated:
            return x
        d = x.shape[1]
        out = x.new_empty((r.N, d))
        out[: r.n_ctx] = x[: r.n_ctx]
        out[r.n_ctx :].view(r.n_q, r.K, d)[:] = x[r.n_ctx :, None, :]
        return out

    def _obs(self, x: Tensor) -> Tensor:
        """Index an N-row tensor down to the T observed rows (identity at K=1)."""
        r = self._rep
        if not r.replicated or x.shape[0] == r.T:
            return x
        return x[r.obs_idx]

    def _mc_reduce(self, Y0_mc: Tensor, Y1_mc: Tensor) -> Tuple[Tensor, ...]:
        """Monte Carlo CEPO targets from the replicate block. Consumes no RNG.

        ``S2`` is the *paired* variance of ``Y1 - Y0``: both arms come from the
        same replicate rows and share their ``eps``, so differencing first
        cancels it. Taking ``[Var(Y1) + Var(Y0)]/K`` instead would inflate the
        reported target noise by roughly twice the outcome variance.
        """
        r = self._rep
        if not r.replicated:
            # No replicates: MU is the single realized draw, matching what
            # LoadPriorDataset already substitutes for MU-less files, so the
            # existing val/point surface is unchanged. S2 = 0 is the prior's
            # "no replicates" marker (distinct from the NaN used for context).
            return (
                Y0_mc,
                Y1_mc,
                torch.zeros_like(Y0_mc),
                1,
            )

        q0 = Y0_mc[r.n_ctx :, 0].view(r.n_q, r.K)
        q1 = Y1_mc[r.n_ctx :, 0].view(r.n_q, r.K)
        qd = q1 - q0

        # NaN, not the realized draw: any consumer reading MU on the context
        # prefix is looking at something that was never computed and should
        # fail loudly rather than silently get ITE-quality values.
        nan_pad = torch.full((r.n_ctx,), float("nan"), dtype=self.dtype)
        MU0 = torch.cat([nan_pad, q0.mean(dim=1)]).unsqueeze(1)
        MU1 = torch.cat([nan_pad, q1.mean(dim=1)]).unsqueeze(1)
        S2 = torch.cat([nan_pad, _mc_mean_var(qd, r.K)]).unsqueeze(1)
        return MU0, MU1, S2, r.K

    # ------------------------------------------------------------------
    # Dataset dispatch
    # ------------------------------------------------------------------

    def generate_dataset(self, params: Dict) -> Tuple[Tensor, ...]:
        mechanism_id = int(params["mechanism_id"])
        T = int(params["seq_len"])
        train_n = int(params.get("train_size", max(1, T // 2)))
        self._rep = self._make_rep(T, train_n)

        dispatch = {
            1: lambda: self._m01_confounding_by_indication(T),
            2: lambda: self._m02_discrete_patient_subtypes(T),
            3: lambda: self._m03_threshold_treatment_policy(T),
            4: lambda: self._m04_count_utilization(T),
            5: lambda: self._m05_censored_survival(T),
            6: lambda: self._m06_customer_uplift(T),
            7: lambda: self._m07_self_selection_education(T),
            8: lambda: self._m08_returns_to_treatment(T),
            9: lambda: self._m09_multisite_random_effects(T),
            10: lambda: self._m10_nonlinear_measurement_factor(T),
            11: lambda: self._m11_interaction_confounding(T),
            12: lambda: self._m12_near_null_strong_confounding(T),
        }
        if mechanism_id not in dispatch:
            raise ValueError(f"Unknown mechanism_id={mechanism_id}")
        return dispatch[mechanism_id]()

